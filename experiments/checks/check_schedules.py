def row_key(reads, alpha_prev, newton_its):
    """The EXPECTED row a grid point lands in, given what the rule reads."""
    args = {"alpha_prev": alpha_prev, "newton_its": newton_its}
    return tuple(args[arg] for arg in reads)


def main():
    assert ALPHA_RULE_DEFAULTS == EXPECTED_DEFAULTS, "default tables differ"
    print("ALPHA_RULE_DEFAULTS equal the recorded defaults: "
          f"{ALPHA_RULE_DEFAULTS == EXPECTED_DEFAULTS}")

    total = 0
    for name, params, reads in CASES:
        key = (name, tuple(sorted(params.items())))
        fn = make_schedule(name, params)
        rows = EXPECTED[key]
        worst = 0.0
        for k in KS:
            for alpha_prev in ALPHA_PREVS:
                for newton_its in NEWTON_ITS:
                    expected = rows[row_key(reads, alpha_prev, newton_its)][k - 1]
                    got = fn(k, alpha_prev, newton_its)
                    assert got == expected, (
                        f"{key} k={k} alpha_prev={alpha_prev} "
                        f"newton_its={newton_its}: {got!r} != {expected!r}")
                    assert math.isfinite(got), f"{key}: non-finite {got!r}"
                    worst = max(worst, abs(got - expected))
                    total += 1
        assert describe(fn) == EXPECTED_DESCRIBE[key], (
            f"{key}: describe={describe(fn)!r} != {EXPECTED_DESCRIBE[key]!r}")
        print(f"{key}  n={len(KS) * len(ALPHA_PREVS) * len(NEWTON_ITS):4d}"
              f"  max|diff|={worst!r}  describe={describe(fn)!r}")

    # --- the overflow protection really is the live path at the defaults ---
    default = make_schedule("double_exponential")
    saturated = [default(k, 0.0, 1) for k in range(1, 31)]
    assert saturated[18] == 10.0, saturated[18]          # k = 19: log_term >= 700
    assert all(math.isfinite(v) for v in saturated)
    try:
        naive = 1.0 * 1.5 ** (1.5**19)
    except OverflowError:
        naive = None
    assert naive is None, "naive evaluation unexpectedly survived k=19"
    print("double_exponential default parameters: naive 1.5**(1.5**19) -> "
          f"OverflowError, log-space value k=19 -> {saturated[18]!r}")

    # --- the `y > 700.0` branch needs k >= 1727 at the default q = 1.5 ------
    worst_big = 0.0
    for name, params, reads in CASES:
        if name != "double_exponential":
            continue
        key = (name, tuple(sorted(params.items())))
        fn = make_schedule(name, params)
        for (k, alpha_prev), expected in EXPECTED_LARGE_K[key].items():
            for newton_its in NEWTON_ITS:
                got = fn(k, alpha_prev, newton_its)
                assert got == expected, (key, k, alpha_prev, newton_its,
                                         got, expected)
                assert math.isfinite(got), (key, k, alpha_prev, got)
                worst_big = max(worst_big, abs(got - expected))
    print("double_exponential y>700.0 branch (k = 1726, 1727, 2000, 10000): "
          f"max|diff|={worst_big!r}")

    # --- pass-through, error message, describe, stopping rules --------------
    custom = lambda k, alpha_prev, newton_its: 1.0 / k    # noqa: E731
    assert make_schedule(custom) is custom
    assert describe(custom) == "custom(<lambda>)"
    assert describe(describe) == "custom(describe)"
    assert make_schedule(describe) is describe
    instance = Geometric(C=0.25, r=1.25)
    assert make_schedule(instance) is instance
    assert make_schedule(instance, {"C": 99.0}) is instance, "params must be ignored"
    assert describe(instance) == "geometric(C=0.25, r=1.25)"
    # `sorted()` is plain ASCII, so 'C' (67) sorts before the lowercase keys.
    assert describe(Constant()) == "constant(C=1)"
    assert describe(DoubleExponential()) == (
        "double_exponential(C=1, alpha_max=10, q=1.5, r=1.5)")
    assert describe(make_schedule("linear")) == "linear(C_max=1e+10, alpha0=1, c=1.5)"
    try:
        make_schedule("no_such_rule")
    except ValueError as exc:
        message = str(exc)
        assert "no_such_rule" in message and "callable" in message
        assert all(name in message for name in ALPHA_RULE_DEFAULTS)
        print(f"unknown name -> ValueError({message!r})")
    else:
        raise AssertionError("unknown rule name did not raise ValueError")

    primal = PrimalIncrement(1e-3)
    assert primal.converged(3, 1.0, 0.5, {"primal_increment": [1e-1, 1e-4]}) is True
