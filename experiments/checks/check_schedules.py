"""Self-contained check of the alpha schedules and the stopping rules.

:mod:`lvpp.schedules` holds the two orthogonal pieces that drive
:meth:`lvpp.solver.LVPP.solve`: the proximal parameter ``alpha_k`` of the mixed
system (LVPP (2.7)) and the test that decides when the outer iteration has
converged.  This script walks a fixed grid of ``k = 1..30``, six ``alpha_prev``
values and four ``newton_its`` values through each of the ten rule
configurations below and compares every returned value against the table of
expected values written out beside the grid.  The table records the value of
the rules in :mod:`lvpp.schedules` on that grid; the check is exact, so any
change of the arithmetic shows up as a mismatch.

The double-exponential rule is the interesting one.  With the default
``r = q = 1.5`` the exponent ``q**k`` grows inside the exponent of ``r``, so
``1.5**(1.5**19)`` overflows a Python float at ``k = 19``; the log-space
evaluation saturates at ``alpha_max`` there instead.  A separate block pins
the same values at ``k = 1726, 1727, 2000, 10000``, where ``k*log(q)`` first
passes 700 and the ``y > 700`` branch is taken.

The remaining checks cover the pass-through of callables and rule instances to
:func:`make_schedule`, the error message for an unknown rule name, the
description built by :func:`describe`, and the two stopping rules:
:class:`PrimalIncrement` (the recorded default, the primal increment below a
tolerance) and :class:`AlphaPlateau` (the hpG paper's criterion, ``alpha``
equal to ``alpha_prev`` from the second step on).

Prints one line per rule configuration and ``SCHEDULES OK`` when every
comparison is exact.

Run from the repository root:

    PETSC_DIR=/home/stefano/firedrake/petsc PETSC_ARCH=arch-firedrake-default \
    OMP_NUM_THREADS=1 /home/stefano/firedrake/venv-firedrake/bin/python \
    experiments/checks/check_schedules.py
"""

